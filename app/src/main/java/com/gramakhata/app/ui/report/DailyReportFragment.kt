package com.gramakhata.app.ui.report

import android.content.Intent
import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import androidx.fragment.app.Fragment
import androidx.fragment.app.viewModels
import com.gramakhata.app.R
import com.gramakhata.app.databinding.FragmentDailyReportBinding
import com.gramakhata.app.util.toDateString
import com.gramakhata.app.util.toDateTimeString
import com.gramakhata.app.util.toRupeeString

/**
 * Daily Collection Report — generates a plain-text summary
 * of all transactions for the current day, shareable via any app.
 */
class DailyReportFragment : Fragment() {

    private var _binding: FragmentDailyReportBinding? = null
    private val binding get() = _binding!!

    private val viewModel: ReportViewModel by viewModels()
    private var reportText: String = ""

    override fun onCreateView(
        inflater: LayoutInflater, container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View {
        _binding = FragmentDailyReportBinding.inflate(inflater, container, false)
        return binding.root
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)

        binding.tvReportDate.text = System.currentTimeMillis().toDateString()

        observeData()

        binding.btnShareReport.setOnClickListener { shareReport() }
    }

    private fun getShopName(): String {
        val prefs = requireContext().getSharedPreferences("shop_prefs", 0)
        return prefs.getString("shop_name", getString(R.string.shop_default_name)) ?: "My Shop"
    }

    private fun observeData() {
        viewModel.totalCreditToday.observe(viewLifecycleOwner) { credit ->
            binding.tvTotalCredit.text = (credit ?: 0.0).toRupeeString()
        }

        viewModel.totalPaymentToday.observe(viewLifecycleOwner) { payment ->
            binding.tvTotalPayment.text = (payment ?: 0.0).toRupeeString()
        }

        viewModel.todayTransactions.observe(viewLifecycleOwner) { transactions ->
            if (transactions.isNullOrEmpty()) {
                binding.tvReportContent.text = getString(R.string.report_no_transactions)
                reportText = getString(R.string.report_no_transactions)
            } else {
                generateReport(transactions)
            }
        }
    }

    private fun generateReport(transactions: List<com.gramakhata.app.data.db.entity.Transaction>) {
        val sb = StringBuilder()
        val shopName = getShopName()
        val dateStr = System.currentTimeMillis().toDateString()

        sb.appendLine("📋 DAILY COLLECTION REPORT")
        sb.appendLine(dateStr)
        sb.appendLine("Shop: $shopName")
        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine()

        var totalCredit = 0.0
        var totalPayment = 0.0

        transactions.forEach { txn ->
            val type = if (txn.isCredit) "CREDIT " else "PAYMENT"
            val sign = if (txn.isCredit) "+" else "-"
            val note = txn.note.ifBlank { "—" }
            val time = txn.timestamp.toDateTimeString()

            sb.appendLine("$type | $sign₹${String.format("%.0f", txn.amount)} | $note")
            sb.appendLine("  $time")
            sb.appendLine()

            if (txn.isCredit) totalCredit += txn.amount
            else totalPayment += txn.amount
        }

        sb.appendLine("━━━━━━━━━━━━━━━━━━━━━━━━")
        sb.appendLine("Total Credit:  ₹${String.format("%.0f", totalCredit)}")
        sb.appendLine("Total Payment: ₹${String.format("%.0f", totalPayment)}")
        sb.appendLine("Net:           ₹${String.format("%.0f", totalCredit - totalPayment)}")
        sb.appendLine()
        sb.appendLine("Generated by Grama Khata")

        reportText = sb.toString()
        binding.tvReportContent.text = reportText
    }

    private fun shareReport() {
        if (reportText.isBlank()) return

        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "Daily Collection Report - ${System.currentTimeMillis().toDateString()}")
            putExtra(Intent.EXTRA_TEXT, reportText)
        }
        startActivity(Intent.createChooser(intent, getString(R.string.report_share)))
    }

    override fun onDestroyView() {
        super.onDestroyView()
        _binding = null
    }
}
